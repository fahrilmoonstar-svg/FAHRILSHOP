// ===== KODE FOR LOOP (DARI DAHULU) =====
const fruits = [
    "Apple",
    "Banana",
    "Mango",
    "Orange",
    "Grape",
    "Watermelon"
];

for (let i = 0; i < fruits.length; i++) {
    console.log(fruits[i]);
}


// ===== KODE WHILE LOOP (YANG BARU) =====
const fruits2 = [
    "Apple",
    "Banana",
    "Mango",
    "Orange"
];

let j = 0;

while (j < fruits2.length) {
    console.log(fruits2[j]);
    j++;
}
